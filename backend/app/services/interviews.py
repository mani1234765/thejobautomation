"""Interview preparation: job-specific question plans, mock answers and feedback.

Provenance is explicit on every question: "job_description" (generated by AI from the actual JD),
"skill_template" or "standard" (JobPilot's own question bank). Nothing is presented as a verified
question the company actually asks.
"""

from __future__ import annotations

import re
import secrets
from typing import Any

from sqlalchemy.orm import Session

from app.ai import service as ai
from app.ai.guards import untrusted
from app.ai.provider import AIUnavailable, LLMError
from app.models import InterviewSession, Job, User
from app.services.applications import _profile_context

STANDARD = [
    ("behavioural", "Tell me about a time you had to deliver under a tight deadline. What did you prioritise?"),
    ("behavioural", "Describe a disagreement with a teammate and how you resolved it."),
    ("behavioural", "Tell me about a mistake you made at work and what you changed afterwards."),
    ("behavioural", "Describe a project you're most proud of. What was your specific contribution?"),
    ("hr", "Walk me through your background and why you're interested in this role."),
    ("hr", "Why do you want to join {company}?"),
    ("hr", "What are your salary expectations and notice period?"),
]
SKILL_TEMPLATES = [
    "How have you used {skill} in a real project? What trade-offs did you make?",
    "What's a difficult problem you solved with {skill}, and how would you approach it differently now?",
]

_QUESTION_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["questions", "focus_areas"],
    "properties": {
        "focus_areas": {"type": "array", "items": {"type": "string"}},
        "questions": {
            "type": "array",
            "items": {
                "type": "object",
                "additionalProperties": False,
                "required": ["category", "question", "rationale"],
                "properties": {
                    "category": {"type": "string", "enum": ["technical", "behavioural", "hr", "role"]},
                    "question": {"type": "string"},
                    "rationale": {"type": "string"},
                },
            },
        },
    },
}
_FEEDBACK_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["scores", "strengths", "improvements", "star", "improved_answer"],
    "properties": {
        "scores": {
            "type": "object",
            "additionalProperties": False,
            "required": ["relevance", "clarity", "structure", "technical_accuracy", "communication"],
            "properties": {
                k: {"type": "integer", "minimum": 1, "maximum": 5}
                for k in ("relevance", "clarity", "structure", "technical_accuracy", "communication")
            },
        },
        "strengths": {"type": "array", "items": {"type": "string"}},
        "improvements": {"type": "array", "items": {"type": "string"}},
        "star": {
            "type": "object",
            "additionalProperties": False,
            "required": ["situation", "task", "action", "result"],
            "properties": {k: {"type": "boolean"} for k in ("situation", "task", "action", "result")},
        },
        "improved_answer": {"type": "string"},
    },
}


def _q(category: str, question: str, rationale: str, provenance: str) -> dict[str, Any]:
    return {
        "id": secrets.token_hex(5),
        "category": category,
        "question": question,
        "rationale": rationale,
        "provenance": provenance,
        "answer": None,
        "feedback": None,
    }


def create_session(db: Session, user: User, job: Job | None, application_id: str | None) -> InterviewSession:
    questions: list[dict[str, Any]] = []
    generated_by = "template"
    focus: list[str] = []
    if job and ai.status()["configured"]:
        try:
            res = ai.complete(
                db,
                user,
                feature="interview_plan",
                system="You are an experienced interview coach.",
                json_schema=_QUESTION_SCHEMA,
                messages=[
                    {
                        "role": "user",
                        "content": "Create 10 interview practice questions for this candidate and job: 4 technical/role "
                        "questions grounded in the job's requirements, 4 behavioural questions tied to the "
                        "candidate's real experience, 2 HR questions. Give a one-line rationale for each that "
                        "cites the requirement or experience it targets. These are practice questions, not "
                        "the company's actual questions.\n\n"
                        f"Candidate:\n{_profile_context(db, user)}\n\nJob: {job.title} at {job.company.name}\n"
                        f"{untrusted('job_description', job.description_text, 10000)}",
                    }
                ],
            )
            data = res.data or {}
            questions = [
                _q(q["category"], q["question"], q["rationale"], "job_description")
                for q in data.get("questions", [])[:14]
            ]
            focus = data.get("focus_areas", [])[:6]
            generated_by = f"llm:{res.model}"
        except (AIUnavailable, LLMError):
            questions = []
    if not questions:
        skills = (job.required_skills if job else [])[:4]
        for s in skills:
            for t in SKILL_TEMPLATES[:1]:
                questions.append(
                    _q("technical", t.format(skill=s), f"The job lists {s} as a requirement.", "skill_template")
                )
        company = job.company.name if job else "this company"
        for cat, q in STANDARD:
            questions.append(_q(cat, q.format(company=company), "Common question for most roles.", "standard"))
        focus = skills
    title = f"{job.title} — {job.company.name}" if job else "General interview practice"
    s = InterviewSession(
        user_id=user.id,
        job_id=job.id if job else None,
        application_id=application_id,
        title=title[:300],
        questions=questions,
        generated_by=generated_by,
    )
    s.questions = [*questions, {"id": "_meta", "focus_areas": focus}]
    db.add(s)
    db.commit()
    return s


_STAR_CUES = {
    "situation": r"\b(when|while|at (my|our)|during|in my (role|internship|job)|our team|the project)\b",
    "task": r"\b(i (was|had) to|my (goal|task|responsibility)|needed to|was asked to|objective)\b",
    "action": r"\b(i (built|designed|led|wrote|created|implemented|analy[sz]ed|proposed|decided|worked|set up|organi[sz]ed|reached out))\b",
    "result": r"(\d+\s*%|\bresult(ed)?\b|\bimproved\b|\breduced\b|\bincreased\b|\bsaved\b|\bas a result\b|\boutcome\b|\blearned\b)",
}


def heuristic_feedback(answer: str) -> dict[str, Any]:
    low = answer.lower()
    star = {k: bool(re.search(p, low)) for k, p in _STAR_CUES.items()}
    words = len(answer.split())
    improvements = []
    for k, ok in star.items():
        if not ok:
            improvements.append(
                {
                    "situation": "Set the scene briefly: where you were and what was at stake.",
                    "task": "State what you specifically were responsible for.",
                    "action": "Describe the concrete steps *you* took, using “I”, not “we”.",
                    "result": "Close with the outcome — ideally a measurable one — and what you learned.",
                }[k]
            )
    if words < 60:
        improvements.append("The answer is short; aim for 150–250 words when speaking.")
    elif words > 400:
        improvements.append("The answer is long; tighten it to the most relevant 2–3 minutes.")
    strengths = [f"Covers the {k}." for k, ok in star.items() if ok]
    return {
        "method": "heuristic",
        "star": star,
        "strengths": strengths,
        "improvements": improvements,
        "scores": None,
        "improved_answer": None,
        "note": "Structure check only. Connect an AI provider for content feedback.",
    }


def evaluate_answer(
    db: Session, user: User, session: InterviewSession, question_id: str, answer: str
) -> dict[str, Any]:
    questions = [dict(q) for q in session.questions]
    q = next((x for x in questions if x["id"] == question_id), None)
    if q is None:
        raise KeyError(question_id)
    feedback: dict[str, Any]
    if ai.status()["configured"]:
        try:
            res = ai.complete(
                db,
                user,
                feature="interview_feedback",
                system="You are a rigorous but encouraging interview coach.",
                json_schema=_FEEDBACK_SCHEMA,
                messages=[
                    {
                        "role": "user",
                        "content": f"Question ({q['category']}): {q['question']}\n\n"
                        f"Candidate's answer:\n{untrusted('candidate_answer', answer, 6000)}\n\n"
                        f"Candidate background:\n{_profile_context(db, user)}\n\n"
                        "Score 1–5 on each dimension, list strengths and specific improvements, mark which "
                        "STAR parts are present, and rewrite the answer in STAR form using ONLY facts the "
                        "candidate stated (mark gaps as [add detail]).",
                    }
                ],
            )
            feedback = {"method": f"llm:{res.model}", **(res.data or {})}
        except (AIUnavailable, LLMError):
            feedback = heuristic_feedback(answer)
    else:
        feedback = heuristic_feedback(answer)
    q["answer"], q["feedback"] = answer, feedback
    session.questions = questions
    db.commit()
    return q


def progress(session: InterviewSession) -> dict[str, int]:
    qs = [q for q in session.questions if q["id"] != "_meta"]
    return {"answered": sum(1 for q in qs if q.get("answer")), "total": len(qs)}
